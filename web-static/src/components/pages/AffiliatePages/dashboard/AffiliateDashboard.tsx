import React, { useEffect, useState } from 'react';
import {
  ArrowRight,
  Building2,
  Check,
  Coins,
  Copy,
  Hash,
  Share2,
  Wallet,
} from 'lucide-react';
import { Link } from 'react-router-dom';
import {
  getAffiliateAccount,
  getAffiliateReferrals,
  getAffiliateSummary,
  getAffiliateWithdrawals,
} from '../../../../api/affiliate';
import type {
  AffiliateAccount,
  AffiliateDashboardSummary,
  AffiliateReferral,
  AffiliateWithdrawal,
} from '../../../../types/affiliate';
import CountryFlag from '../CountryFlag';

const AffiliateDashboard: React.FC = () => {
  const [summary, setSummary] = useState<AffiliateDashboardSummary | null>(
    null
  );
  const [error, setError] = useState('');
  const [account, setAccount] = useState<AffiliateAccount | null>(null);
  const [referrals, setReferrals] = useState<AffiliateReferral[]>([]);
  const [withdrawals, setWithdrawals] = useState<AffiliateWithdrawal[]>([]);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    getAffiliateSummary()
      .then(setSummary)
      .catch((e) =>
        setError(e instanceof Error ? e.message : 'Could not load dashboard.')
      );
    getAffiliateAccount()
      .then(setAccount)
      .catch(() => undefined);
    getAffiliateReferrals()
      .then(setReferrals)
      .catch(() => undefined);
    getAffiliateWithdrawals()
      .then(setWithdrawals)
      .catch(() => undefined);
  }, []);

  const copyReferralCode = async () => {
    if (!account?.referral_code) return;
    try {
      await navigator.clipboard.writeText(account.referral_code);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setError('Could not copy the referral code. Please copy it manually.');
    }
  };

  const availableCoins = Number(summary?.available_coins ?? 0);
  const totalCoinsWithdrawn = Number(
    summary?.total_coins_withdrawn ??
      withdrawals.reduce(
        (total, withdrawal) => total + Number(withdrawal.coins ?? 0),
        0
      )
  );
  const metrics = [
    {
      label: 'Businesses joined',
      value: summary?.total_referrals ?? 0,
      unit: 'Businesses',
      icon: Building2,
      tint: 'bg-orange-50 text-primary',
    },
    {
      label: 'Tracking numbers',
      value: Number(summary?.total_tracking_numbers ?? 0).toLocaleString(),
      unit: 'Generated by referrals',
      icon: Hash,
      tint: 'bg-blue-50 text-blue-600',
    },
    {
      label: 'Total coins withdrawn',
      value: totalCoinsWithdrawn.toLocaleString(),
      unit: 'Coins - lifetime',
      icon: Coins,
      tint: 'bg-emerald-50 text-emerald-600',
    },
    {
      label: 'Available coins',
      value: availableCoins.toLocaleString(),
      unit: 'Coins - ready to withdraw',
      icon: Wallet,
      tint: 'bg-amber-50 text-amber-600',
    },
  ];

  return (
    <div className="space-y-6">
      <section className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <p className="text-sm font-medium text-primary">
            Your affiliate journey
          </p>
          <h2 className="mt-1 text-2xl font-bold sm:text-3xl">
            Welcome back{account?.name ? `, ${account.name.split(' ')[0]}` : ''}
            !
          </h2>
          <p className="mt-1 text-sm text-slate-500">
            Here’s how your referrals are doing.
          </p>
        </div>
        <Link
          className="inline-flex items-center gap-2 text-sm font-semibold text-primary hover:underline"
          to="/affiliate/dashboard/referrals"
        >
          View referrals <ArrowRight size={16} />
        </Link>
      </section>

      {error && (
        <p
          className="rounded border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700"
          role="alert"
        >
          {error}
        </p>
      )}
      {!summary ? (
        <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
          {metrics.map(({ label, icon: Icon, tint }) => (
            <div
              key={label}
              className="h-32 animate-pulse rounded-lg border border-slate-100 bg-white p-5"
            >
              <div className="flex justify-between">
                <span className="h-3 w-28 rounded bg-slate-100" />
                <span
                  className={`grid h-9 w-9 place-items-center rounded ${tint}`}
                >
                  <Icon size={17} />
                </span>
              </div>
              <div className="mt-5 h-7 w-20 rounded bg-slate-100" />
            </div>
          ))}
        </div>
      ) : (
        <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
          {metrics.map(({ label, value, unit, icon: Icon, tint }) => (
            <article
              className="rounded-lg border border-slate-100 bg-white p-5 shadow-sm shadow-slate-900/[0.03]"
              key={label}
            >
              <div className="flex items-start justify-between gap-3">
                <span className="text-sm font-medium text-slate-500">
                  {label}
                </span>
                <span
                  className={`grid h-9 w-9 shrink-0 place-items-center rounded ${tint}`}
                >
                  <Icon size={18} />
                </span>
              </div>
              <strong className="mt-3 block text-2xl font-bold tracking-tight">
                {value}
              </strong>
              <span className="mt-1 block text-xs text-slate-400">{unit}</span>
            </article>
          ))}
        </div>
      )}

      <div className="grid gap-4 lg:grid-cols-2">
        <section className="rounded-lg border border-orange-100 bg-gradient-to-br from-orange-50 to-white p-5 sm:p-6">
          <div className="flex items-center gap-2 text-sm font-semibold text-primary">
            <Share2 size={17} /> Your referral code
          </div>
          {account?.referral_code ? (
            <div className="mt-3 flex flex-wrap items-center justify-between gap-3">
              <strong className="text-3xl font-extrabold tracking-wide">
                {account.referral_code}
              </strong>
              <button
                className="inline-flex items-center gap-2 rounded border border-orange-200 bg-white px-4 py-2.5 text-sm font-semibold text-primary transition hover:bg-orange-50"
                onClick={copyReferralCode}
              >
                {copied ? <Check size={16} /> : <Copy size={16} />}
                {copied ? 'Copied' : 'Copy code'}
              </button>
            </div>
          ) : (
            <p className="mt-3 text-sm text-slate-500">
              Loading your referral code...
            </p>
          )}
          <p className="mt-3 text-sm leading-6 text-slate-600">
            Share this code with businesses. You earn coins when they generate
            tracking numbers.
          </p>
        </section>
        <section className="rounded-lg border border-slate-100 bg-white p-5 sm:p-6">
          <div className="flex items-center justify-between">
            <div>
              <h3 className="font-bold">How it works</h3>
              <p className="mt-1 text-sm text-slate-500">
                A simple way to earn with your network.
              </p>
            </div>
            <span className="grid h-10 w-10 place-items-center rounded-full bg-orange-50 text-primary">
              <Coins size={20} />
            </span>
          </div>
          <ol className="mt-4 grid gap-3 sm:grid-cols-3">
            {[
              ['01', 'Share your code'],
              ['02', 'They create trackings'],
              ['03', 'You earn coins'],
            ].map(([number, label]) => (
              <li className="flex items-center gap-2.5 text-sm" key={number}>
                <span className="grid h-7 w-7 shrink-0 place-items-center rounded-full bg-slate-100 text-xs font-bold text-slate-600">
                  {number}
                </span>
                <span className="font-medium text-slate-700">{label}</span>
              </li>
            ))}
          </ol>
        </section>
      </div>

      <section className="overflow-hidden rounded-lg border border-slate-100 bg-white shadow-sm shadow-slate-900/[0.03]">
        <div className="flex items-center justify-between border-b border-slate-100 px-5 py-4">
          <div>
            <h3 className="font-bold">Recent referrals</h3>
            <p className="mt-0.5 text-xs text-slate-500">
              Businesses you’ve helped join TrackerrGo.
            </p>
          </div>
          <Link
            className="text-sm font-semibold text-primary hover:underline"
            to="/affiliate/dashboard/referrals"
          >
            View all
          </Link>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full min-w-[830px] border-collapse text-left">
            <thead className="bg-slate-50">
              <tr>
                {[
                  'Business name',
                  'Country',
                  'Joined on',
                  'Tracking numbers',
                  'Coins earned',
                  'Status',
                ].map((heading) => (
                  <th
                    className="px-5 py-3 text-xs font-semibold uppercase tracking-wide text-slate-500"
                    key={heading}
                  >
                    {heading}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {referrals.slice(0, 5).map((referral) => (
                <tr className="hover:bg-slate-50/70" key={referral.id}>
                  <td className="px-5 py-3.5 text-sm font-semibold">
                    <CountryFlag country={referral.country} />
                    {referral.business_name ??
                      referral.name ??
                      'Business referral'}
                  </td>
                  <td className="px-5 py-3.5 text-sm text-slate-500">
                    {referral.country ?? '—'}
                  </td>
                  <td className="px-5 py-3.5 text-sm text-slate-500">
                    {referral.created_at
                      ? new Date(referral.created_at).toLocaleDateString()
                      : '—'}
                  </td>
                  <td className="px-5 py-3.5 text-sm text-slate-600">
                    {referral.tracking_numbers ?? 0}
                  </td>
                  <td className="px-5 py-3.5 text-sm font-semibold">
                    {Number(referral.coins_earned ?? 0).toLocaleString()}
                  </td>
                  <td className="px-5 py-3.5">
                    <span
                      className={`rounded-full px-2.5 py-1 text-xs font-semibold ${['active', 'completed'].includes((referral.status ?? 'pending').toLowerCase()) ? 'bg-emerald-50 text-emerald-700' : 'bg-amber-50 text-amber-700'}`}
                    >
                      {referral.status ?? 'Pending'}
                    </span>
                  </td>
                </tr>
              ))}
              {!referrals.length && (
                <tr>
                  <td
                    className="px-5 py-8 text-center text-sm text-slate-500"
                    colSpan={6}
                  >
                    Your referrals will appear here once a business joins.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
};

export default AffiliateDashboard;
